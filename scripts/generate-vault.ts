/**
 * Generate a synthetic Obsidian vault for development and stress testing.
 *
 *   npm run generate                 # 200 notes into ./dev-vault
 *   npm run generate -- --nodes 10000
 *   npm run generate -- --seed 42 --out ./other-vault
 *
 * Only directories previously created by this script (marked by a dot-file)
 * are cleared, so pointing --out at a real vault is refused.
 */
import { existsSync, mkdirSync, readdirSync, rmSync, utimesSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { makeDocx, makePdf } from "./lib/fixtures";

interface Options {
	nodes: number;
	out: string;
	seed: number;
}

const MARKER = ".nebula-generated";
const FIXTURE_DIR = "Attachments";
const FIXTURE_COUNT = 6; // per type, so 12 files total
const MAX_OUT_LINKS = 12;

const FOLDERS = ["Inbox", "Projects", "Projects/Alpha", "Projects/Beta", "Research", "Research/Graphics", "Journal", "Reference"];
const TAGS = [
	"project", "idea", "todo", "meeting", "research", "reading", "draft", "review", "design", "math",
	"shader", "physics", "graph", "writing", "archive", "daily", "api", "bug", "spec", "music",
	"travel", "finance", "health", "learning",
];
const WORDS = [
	"lattice", "signal", "orbit", "vector", "prism", "halo", "ember", "drift", "quartz", "lumen",
	"cascade", "fractal", "nexus", "pulse", "relay", "cipher", "meridian", "spectrum", "anchor", "thread",
	"harbor", "canvas", "ledger", "beacon", "sketch", "compass", "module", "garden", "column", "summit",
];

function parseArgs(argv: string[]): Options {
	const opts: Options = { nodes: 200, out: resolve("dev-vault"), seed: 1 };
	for (let i = 0; i < argv.length; i++) {
		const arg = argv[i];
		const next = (): string => {
			const v = argv[++i];
			if (v === undefined) throw new Error(`Missing value after ${arg}`);
			return v;
		};
		if (arg === "--nodes") opts.nodes = Number(next());
		else if (arg === "--out") opts.out = resolve(next());
		else if (arg === "--seed") opts.seed = Number(next());
		else throw new Error(`Unknown argument: ${arg}`);
	}
	if (!Number.isInteger(opts.nodes) || opts.nodes < 1) throw new Error("--nodes must be a positive integer");
	return opts;
}

/** Deterministic PRNG so a given seed always yields the same vault. */
function mulberry32(seed: number): () => number {
	let s = seed >>> 0;
	return () => {
		s = (s + 0x6d2b79f5) >>> 0;
		let t = s;
		t = Math.imul(t ^ (t >>> 15), t | 1);
		t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};
}

/** Prepare the output directory, refusing to touch anything not created by this script. */
function prepareOutDir(out: string): void {
	if (!existsSync(out)) {
		mkdirSync(out, { recursive: true });
	} else if (!existsSync(join(out, MARKER))) {
		if (readdirSync(out).length > 0) {
			throw new Error(`Refusing to write into non-empty directory without ${MARKER}: ${out}`);
		}
	}
	for (const entry of readdirSync(out)) {
		if (entry === ".obsidian" || entry === MARKER) continue;
		rmSync(join(out, entry), { recursive: true, force: true });
	}
	writeFileSync(join(out, MARKER), "Generated by scripts/generate-vault.ts. Safe to delete.\n");

	const obsidianDir = join(out, ".obsidian");
	mkdirSync(obsidianDir, { recursive: true });
	const communityPlugins = join(obsidianDir, "community-plugins.json");
	if (!existsSync(communityPlugins)) writeFileSync(communityPlugins, JSON.stringify(["nebula-graph"], null, 2));
	const appJson = join(obsidianDir, "app.json");
	if (!existsSync(appJson)) writeFileSync(appJson, "{}\n");
}

function sentence(rnd: () => number, min: number, max: number): string {
	const n = min + Math.floor(rnd() * (max - min + 1));
	const words: string[] = [];
	for (let i = 0; i < n; i++) words.push(pick(rnd, WORDS));
	const s = words.join(" ");
	return s.charAt(0).toUpperCase() + s.slice(1) + ".";
}

function pick<T>(rnd: () => number, items: readonly T[]): T {
	const v = items[Math.floor(rnd() * items.length)];
	if (v === undefined) throw new Error("pick() called with empty list");
	return v;
}

/** Heavy-tailed out-degree: most notes link a little, a few link a lot. */
function outDegree(rnd: () => number): number {
	const k = Math.floor(Math.pow(1 - rnd(), -1 / 1.5)) - 1;
	return Math.max(0, Math.min(MAX_OUT_LINKS, k));
}

interface NoteSpec {
	title: string;
	path: string;
	folder: string;
	tags: string[];
	ctime: number;
	mtime: number;
	targets: number[];
}

function planNotes(opts: Options, rnd: () => number): NoteSpec[] {
	const now = Date.now();
	const twoYears = 2 * 365 * 24 * 3600 * 1000;
	const notes: NoteSpec[] = [];

	for (let i = 0; i < opts.nodes; i++) {
		const title = `${capitalize(pick(rnd, WORDS))} ${pick(rnd, WORDS)} ${String(i).padStart(5, "0")}`;
		const folder = pick(rnd, FOLDERS);
		const tagCount = Math.floor(rnd() * 4);
		const tags: string[] = [];
		for (let t = 0; t < tagCount; t++) {
			// Zipf-like: squaring the uniform draw favours the first tags in the list.
			const tag = TAGS[Math.floor(Math.pow(rnd(), 2) * TAGS.length)];
			if (tag !== undefined && !tags.includes(tag)) tags.push(tag);
		}
		const ctime = now - Math.floor(rnd() * twoYears);
		const mtime = ctime + Math.floor(rnd() * (now - ctime));
		notes.push({ title, path: `${folder}/${title}.md`, folder, tags, ctime, mtime, targets: [] });
	}

	// Preferential attachment: each note starts with one slot in the pool, and every
	// time it gains a link it gets another. Sampling from the pool gives a power law.
	const pool: number[] = [];
	for (let i = 0; i < notes.length; i++) pool.push(i);
	for (let i = 0; i < notes.length; i++) {
		const spec = notes[i];
		if (!spec) continue;
		const wanted = outDegree(rnd);
		for (let attempt = 0; spec.targets.length < wanted && attempt < wanted * 10; attempt++) {
			const j = pick(rnd, pool);
			if (j === i || spec.targets.includes(j)) continue;
			spec.targets.push(j);
			pool.push(j);
		}
		pool.push(i);
	}
	return notes;
}

function capitalize(s: string): string {
	return s.charAt(0).toUpperCase() + s.slice(1);
}

function renderNote(spec: NoteSpec, notes: NoteSpec[], attachments: string[], rnd: () => number): string {
	const created = new Date(spec.ctime).toISOString().slice(0, 10);
	const lines: string[] = ["---", `created: ${created}`, "---", "", `# ${spec.title}`, ""];

	const paragraphs = 1 + Math.floor(rnd() * 3);
	for (let p = 0; p < paragraphs; p++) {
		lines.push(`${sentence(rnd, 6, 14)} ${sentence(rnd, 6, 14)}`, "");
	}

	if (spec.targets.length > 0) {
		lines.push("## Related", "");
		for (const j of spec.targets) {
			const target = notes[j];
			if (target) lines.push(`- [[${target.title}]] ${sentence(rnd, 3, 6)}`);
		}
		lines.push("");
	}

	if (attachments.length > 0 && rnd() < 0.08) {
		lines.push(`See [[${pick(rnd, attachments)}]].`, "");
	}

	if (spec.tags.length > 0) {
		lines.push(spec.tags.map((t) => `#${t}`).join(" "), "");
	}
	return lines.join("\n");
}

function generateAttachments(out: string, rnd: () => number): string[] {
	const dir = join(out, FIXTURE_DIR);
	mkdirSync(dir, { recursive: true });
	const names: string[] = [];
	for (let i = 1; i <= FIXTURE_COUNT; i++) {
		const topic = pick(rnd, WORDS);
		const pdfName = `Spec ${i} ${topic}.pdf`;
		writeFileSync(
			join(dir, pdfName),
			makePdf(`Spec ${i}: ${topic} notes`, [
				`This fixture simulates a PDF attachment about ${topic}.`,
				"It exists so the graph can show non-markdown nodes.",
			]),
		);
		const docxName = `Brief ${i} ${topic}.docx`;
		writeFileSync(
			join(dir, docxName),
			makeDocx([`Brief ${i}: ${topic}`, `This fixture simulates a Word document about ${topic}.`]),
		);
		names.push(pdfName, docxName);
	}
	return names;
}

function writeNotes(out: string, notes: NoteSpec[], attachments: string[], rnd: () => number): void {
	for (const spec of notes) {
		const dir = join(out, spec.folder);
		mkdirSync(dir, { recursive: true });
		const file = join(out, spec.path);
		writeFileSync(file, renderNote(spec, notes, attachments, rnd));
		const seconds = spec.mtime / 1000;
		utimesSync(file, seconds, seconds);
	}
}

function main(): void {
	const opts = parseArgs(process.argv.slice(2));
	const rnd = mulberry32(opts.seed);

	prepareOutDir(opts.out);
	const notes = planNotes(opts, rnd);
	const attachments = generateAttachments(opts.out, rnd);
	writeNotes(opts.out, notes, attachments, rnd);

	const edges = notes.reduce((n, s) => n + s.targets.length, 0);
	const tagged = notes.filter((s) => s.tags.length > 0).length;
	const folders = new Set(notes.map((s) => s.folder)).size;
	console.log(
		`Generated ${notes.length} notes, ${edges} links, ${tagged} tagged, ${folders} folders, ` +
			`${attachments.length} attachments in ${opts.out} (seed ${opts.seed}).`,
	);
}

main();
